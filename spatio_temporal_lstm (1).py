#calculating haversine distance to allocate nerarest tower
def haversine(lat1, lon1, lat2, lon2):
    R = 6371000  # Earth radius in meters

    lat1, lon1, lat2, lon2 = map(radians, [lat1, lon1, lat2, lon2])

    dlat = lat2 - lat1
    dlon = lon2 - lon1

    a = sin(dlat/2)**2 + cos(lat1) * cos(lat2) * sin(dlon/2)**2
    c = 2 * atan2(sqrt(a), sqrt(1 - a))

    return R * c

# Create empty columns
for tower_name in towers:
    df[f"distance_{tower_name}_m"] = 0.0

# Compute distances row by row
for index, row in df.iterrows():
    phone_lat = row["Latitude"]
    phone_lon = row["Longitude"]

    for tower_name, (tower_lat, tower_lon) in towers.items():
        distance = haversine(phone_lat, phone_lon, tower_lat, tower_lon)
        df.at[index, f"distance_{tower_name}_m"] = distance

