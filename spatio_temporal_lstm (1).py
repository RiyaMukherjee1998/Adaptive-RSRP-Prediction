import numpy as np
from sklearn.preprocessing import MinMaxScaler

# Ensure df is sorted by Timestamp for time-series features
df = df.sort_values(by='Timestamp').reset_index(drop=True)

# Create RSRP_lag1: lagged RSRP_dBm
df["RSRP_lag1"] = df["RSRP_dBm"].shift(1)

# Create log_distance: logarithm of distance_to_nearest_tower_m
# Add a small constant to avoid log(0) in case of zero or very small distances.
df["log_distance"] = np.log(df["distance_to_nearest_tower_m"] + 1e-6)

# Drop rows with NaN values introduced by shifting (typically the first row) and in the newly created features
df.dropna(subset=["RSRP_lag1", "log_distance"], inplace=True)

# IMPORTANT: RSRP_lag1 will be implicitly handled by the sequence creation, so we don't include it in features here
features = ["RSRP_lag1", "log_distance", "Speed_kmph", "Scenario_code", "Mobility_code"]
target = "RSRP_dBm"

X_data = df[features].values
y_data = df[target].values.reshape(-1,1)

# =========================
# 2. SCALING
# =========================

scaler_X = MinMaxScaler()
scaler_y = MinMaxScaler()

X_scaled = scaler_X.fit_transform(X_data)
y_scaled = scaler_y.fit_transform(y_data)

# =========================
# 3. CREATE MULTIVARIATE SEQUENCES
# =========================

def create_sequences_multivariate(X, y, seq_length=5):
    X_seq, y_seq = [], []

    for i in range(len(X) - seq_length):
        X_seq.append(X[i:i+seq_length])
        y_seq.append(y[i+seq_length])

    return np.array(X_seq), np.array(y_seq)

seq_length = 5

X_seq, y_seq = create_sequences_multivariate(X_scaled, y_scaled, seq_length)

# =========================
# 4. BUILD LSTM MODEL
# =========================

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Input

model = Sequential([
    Input(shape=(seq_length, X_seq.shape[2])),  # (time_steps, features)
    LSTM(32),
    Dense(1)
])

model.compile(optimizer='adam', loss='mse')

# =========================
# 5. ADAPTIVE TRAINING
# =========================

predictions = []
actuals = []

initial_size = 500   # increased for stability

# initial training (important)
model.fit(
    X_seq[:initial_size],
    y_seq[:initial_size],
    epochs=20,
    batch_size=32,
    verbose=0
)

# adaptive loop
for i in range(initial_size, len(X_seq)):

    x_input = X_seq[i].reshape(1, seq_length, X_seq.shape[2])

    # prediction
    pred = model.predict(x_input, verbose=0)[0][0]

    predictions.append(pred)
    actuals.append(y_seq[i])

    # controlled adaptive update (IMPORTANT)
    if i % 5 == 0:
        model.fit(x_input, np.array([y_seq[i]]), epochs=1, verbose=0)

