def evaluate(actual, pred):
    r2 = r2_score(actual, pred)
    rmse = np.sqrt(mean_squared_error(actual, pred))
    return r2, rmse

# ---------- Adaptive LSTM ----------
def adaptive_lstm(signal, seq_length=5, initial_size=300):
    scaler = MinMaxScaler()
    signal_scaled = scaler.fit_transform(signal.reshape(-1,1))

    def create_seq(data):
        X, y = [], []
        for i in range(len(data)-seq_length):
            X.append(data[i:i+seq_length])
            y.append(data[i+seq_length])
        return np.array(X), np.array(y)

    X, y = create_seq(signal_scaled)
    X = X.reshape((X.shape[0], X.shape[1], 1))

    model = Sequential([
        Input(shape=(seq_length, 1)),
        LSTM(32),
        Dense(1)
    ])
    model.compile(optimizer='adam', loss='mse')

    model.fit(X[:initial_size], y[:initial_size], epochs=5, verbose=0)

    preds, actuals = [], []

    for i in range(initial_size, len(X)):
        x_input = X[i].reshape(1, seq_length, 1)

        pred = model.predict(x_input, verbose=0)[0][0]

        preds.append(pred)
        actuals.append(y[i])

        model.fit(x_input, np.array([y[i]]), epochs=1, verbose=0)

    preds = scaler.inverse_transform(np.array(preds).reshape(-1,1)).flatten()
    actuals = scaler.inverse_transform(np.array(actuals).reshape(-1,1)).flatten()

    return evaluate(actuals, preds)

