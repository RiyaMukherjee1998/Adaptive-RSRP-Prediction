import numpy as np
from sklearn.preprocessing import MinMaxScaler
import pandas as pd

# Load the dataset with the distance feature
df = pd.read_csv("/content/dataset_with_distance_feature.csv")

# Create the log_distance feature, handling potential zeros or negative values
df["log_distance"] = np.log1p(df["distance_to_nearest_tower_m"])

# Use spatial + environmental features (sequence will capture time)
features = ["log_distance", "Speed_kmph", "Scenario_code", "Mobility_code"]
target = "RSRP_dBm"

X_data = df[features].values
y_data = df[target].values.reshape(-1, 1)

# =========================
# 2. SCALING
# =========================

scaler_X = MinMaxScaler()
scaler_y = MinMaxScaler()

X_scaled = scaler_X.fit_transform(X_data)
y_scaled = scaler_y.fit_transform(y_data)

# =========================
# 3. CREATE MULTIVARIATE SEQUENCES
# =========================

def create_sequences_multivariate(X, y, seq_length=5):
    X_seq, y_seq = [], []

    for i in range(len(X) - seq_length):
        X_seq.append(X[i:i+seq_length])   # all features
        y_seq.append(y[i+seq_length])

    return np.array(X_seq), np.array(y_seq)

seq_length = 5
X_seq, y_seq = create_sequences_multivariate(X_scaled, y_scaled, seq_length)

# =========================
# 4. BUILD GRU MODEL
# =========================

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import GRU, Dense, Input

model = Sequential([
    Input(shape=(seq_length, X_seq.shape[2])),  # (time_steps, features)
    GRU(32),
    Dense(1)
])

model.compile(optimizer='adam', loss='mse')

# =========================
# 5. ADAPTIVE TRAINING
# =========================

predictions = []
actuals = []

initial_size = 500  # larger for stability

# initial training
model.fit(
    X_seq[:initial_size],
    y_seq[:initial_size],
    epochs=20,
    batch_size=32,
    verbose=0
)

# adaptive loop
for i in range(initial_size, len(X_seq)):

    x_input = X_seq[i].reshape(1, seq_length, X_seq.shape[2])

    # prediction
    pred = model.predict(x_input, verbose=0)[0][0]

    predictions.append(pred)
    actuals.append(y_seq[i])

    # controlled update (avoid instability)
    if i % 5 == 0:
        model.fit(x_input, np.array([y_seq[i]]), epochs=1, verbose=0)

# =========================
# 6. INVERSE TRANSFORM
# =========================

predictions = scaler_y.inverse_transform(np.array(predictions).reshape(-1,1))
actuals = scaler_y.inverse_transform(np.array(actuals).reshape(-1,1))

predictions = predictions.flatten()
actuals = actuals.flatten()

# =========================
# 7. EVALUATION
# =========================

from sklearn.metrics import r2_score, mean_squared_error

r2 = r2_score(actuals, predictions)
rmse = np.sqrt(mean_squared_error(actuals, predictions))

print("Adaptive Spatio-Temporal GRU R²:", r2)
print("Adaptive Spatio-Temporal GRU RMSE:", rmse)

import matplotlib.pyplot as plt

plt.figure(figsize=(10,5))

plt.plot(actuals, label="Measured RSRP", linewidth=2)
plt.plot(predictions, label="Predicted RSRP (Adaptive Model)", linestyle="--")

plt.xlabel("Sample Index (Time)")
plt.ylabel("RSRP (dBm)")
plt.title("Measured vs Predicted RSRP using Adaptive GRU Model")

plt.legend()
plt.grid(True)

